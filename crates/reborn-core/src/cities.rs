/// Every country in the list once, A to Z.
pub fn countries() -> Vec<&'static str> {
    let mut all: Vec<&str> = CITIES.iter().map(|(_, country)| *country).collect();
    all.sort_unstable();
    all.dedup();
    all
}

/// The cities of `country` as indices into `CITIES`, best known first.
pub fn cities_in(country: &str) -> Vec<usize> {
    (0..CITIES.len())
        .filter(|&i| CITIES[i].1 == country)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_ascii_unique_and_short() {
        assert!(CITIES.len() >= 300);
        let mut seen = std::collections::HashSet::new();
        for (name, country) in CITIES {
            assert!(name.is_ascii() && country.is_ascii(), "{name}");
            assert!(name.len() <= 40, "{name}");
            assert!(seen.insert(name.to_ascii_lowercase()), "duplicate {name}");
        }
    }

    #[test]
    fn cities_are_picked_country_first() {
        let all = countries();
        assert!(all.windows(2).all(|w| w[0] < w[1]));
        assert_eq!(all.len(), 156);
        assert_eq!(all[0], "Afghanistan");
        let france: Vec<&str> = cities_in("France").iter().map(|&i| CITIES[i].0).collect();
        assert_eq!(france[0], "Paris");
        assert!(cities_in("Atlantis").is_empty());
        // Every city is reachable through its country.
        let total: usize = all.iter().map(|c| cities_in(c).len()).sum();
        assert_eq!(total, CITIES.len());
    }
}
